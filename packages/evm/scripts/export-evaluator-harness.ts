/**
 * Writes harness/evaluator-harness.json: the runtime code of EvaluatorHarness,
 * the libraries it links, and EvenLastByteCondition, by address.
 *
 * Other repos test off-chain evaluators against the contract with it: load
 * every entry of `code` into an anvil with `anvil_setCode`, then `eth_call`
 * `EvaluatorHarness.evaluate`. No deployment, no Hardhat needed there.
 *
 *   yarn hardhat run scripts/export-evaluator-harness.ts
 */
import { ContractFactory } from "ethers";
import { writeFileSync, mkdirSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import hre, { network } from "hardhat";

const here = path.dirname(fileURLToPath(import.meta.url));
const out = path.resolve(here, "../harness/evaluator-harness.json");

const { ethers } = await network.create();
const [signer] = await ethers.getSigners();

// libraries from bytecode only: their ABIs use enum types ethers can't parse
const library = async (name: string) => {
  const { bytecode } = await hre.artifacts.readArtifact(name);
  const deployed = await new ContractFactory([], bytecode, signer).deploy();
  return deployed.getAddress();
};
const libraries = {
  CustomConditionChecker: await library("CustomConditionChecker"),
  WithinRatioChecker: await library("WithinRatioChecker"),
};

const harness = await (
  await ethers.getContractFactory("EvaluatorHarness", { libraries })
).deploy();
const customCondition = await (
  await ethers.getContractFactory("EvenLastByteCondition")
).deploy();

const addresses = {
  EvaluatorHarness: await harness.getAddress(),
  EvenLastByteCondition: await customCondition.getAddress(),
  ...libraries,
};

const code: Record<string, string> = {};
for (const address of Object.values(addresses)) {
  code[address.toLowerCase()] = await ethers.provider.getCode(address);
}

const { abi } = await hre.artifacts.readArtifact("EvaluatorHarness");

mkdirSync(path.dirname(out), { recursive: true });
writeFileSync(
  out,
  JSON.stringify(
    {
      description:
        "Roles v3 EvaluatorHarness for anvil: load `code` with anvil_setCode, then eth_call `evaluate` on `addresses.EvaluatorHarness`. Generated by scripts/export-evaluator-harness.ts.",
      addresses,
      code,
      abi,
    },
    null,
    2,
  ) + "\n",
);
console.log(`wrote ${path.relative(process.cwd(), out)}`);
console.log(addresses);
