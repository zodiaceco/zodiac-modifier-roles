import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const evmRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const artifactsDir = path.join(evmRoot, "build", "artifacts");
const outDir = path.join(evmRoot, "build");

const CONTRACTS = [
  ["rolesAbi", "contracts/Roles.sol/Roles.json"],
  ["evaluatorAbi", "contracts/evaluator/Evaluator.sol/Evaluator.json"],
  ["integrityAbi", "contracts/evaluator/Integrity.sol/Integrity.json"],
  [
    "avatarIsOwnerOfERC721Abi",
    "contracts/periphery/AvatarIsOwnerOfERC721.sol/AvatarIsOwnerOfERC721.json",
  ],
  [
    "multiSendUnwrapperAbi",
    "contracts/periphery/unwrappers/MultiSendUnwrapper.sol/MultiSendUnwrapper.json",
  ],
  [
    "signTypedMessageLibAbi",
    "contracts/periphery/signing/SignTypedMessageLib.sol/SignTypedMessageLib.json",
  ],
];

const IDENTIFIER_RE = /^[a-zA-Z_$][a-zA-Z0-9_$]*$/;

function toReadonlyType(value, indent = 0) {
  if (Array.isArray(value)) {
    if (value.length === 0) return "readonly []";
    const pad = " ".repeat(indent + 2);
    const closePad = " ".repeat(indent);
    const items = value.map((item) => `${pad}${toReadonlyType(item, indent + 2)}`);
    return `readonly [\n${items.join(",\n")}\n${closePad}]`;
  }
  if (value !== null && typeof value === "object") {
    const entries = Object.entries(value);
    if (entries.length === 0) return "{}";
    const pad = " ".repeat(indent + 2);
    const closePad = " ".repeat(indent);
    const fields = entries.map(([k, v]) => {
      const key = IDENTIFIER_RE.test(k) ? k : JSON.stringify(k);
      return `${pad}readonly ${key}: ${toReadonlyType(v, indent + 2)};`;
    });
    return `{\n${fields.join("\n")}\n${closePad}}`;
  }
  return JSON.stringify(value);
}

const jsLines = ["// Generated by scripts/export-abis.mjs"];
const dtsLines = ["// Generated by scripts/export-abis.mjs"];

for (const [exportName, artifactRelPath] of CONTRACTS) {
  const artifactPath = path.join(artifactsDir, artifactRelPath);
  const { abi } = JSON.parse(readFileSync(artifactPath, "utf8"));
  jsLines.push(`export const ${exportName} = ${JSON.stringify(abi, null, 2)};`);
  dtsLines.push(`export declare const ${exportName}: ${toReadonlyType(abi)};`);
}

mkdirSync(outDir, { recursive: true });
writeFileSync(path.join(outDir, "abis.js"), jsLines.join("\n\n") + "\n");
writeFileSync(path.join(outDir, "abis.d.ts"), dtsLines.join("\n\n") + "\n");
